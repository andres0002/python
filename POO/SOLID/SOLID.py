# Principios SOLID:
# 1. Mantenibilidad.
# 2. Reusabilidad.
# 3. Legibilidad.
# 4. Extensibilidad.

# Los principios SOLID son: 
# S -> SRP -> Principio de Responsabilidad Única, Cada componente debe tener una sola
# responsabilidad.
# O -> OCP -> Principio Abierto/Cerrado, Los componentes deben poder extenderse, pero
# no modificarse.
# L -> LSP -> Principio de Sustitución de Liskov, Los objetos de una clase base pueden
# reemplazarse por objetos de una clase derivada.
# I -> ISP -> Principio de Segregación de Interfaces, No se debe obligar a los consumidores
# a depender de interfaces que no utilizan.
# D -> DIP -> Principio de Inversión de Dependencia, Se debe depender de abstracciones,
# no de implementaciones concretas.