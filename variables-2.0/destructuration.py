# Desempaquetado o Desestructuración -> Para asignar values a variables de forma particular.

# tuplas (tuple)
data_tupla = ("Andres", "Ramirez")
name, lastname = data_tupla
print(f"Name: {name}, Lastname: {lastname}.")

# listas (list)
data_list = ["Andres2", "Ramirez2"]
name, lastname = data_list
print(f"Name: {name}, Lastname: {lastname}.")

# conjuntos (set)
data_set = {"Andres3", "Ramirez3"}
name, lastname = data_set
print(f"Name: {name}, Lastname: {lastname}.")