# == -> Es igual que.
es_igual_que = 5 == 6
print(f"== -> {es_igual_que}")

# != -> Es distinto de.
es_distinto_de = 5 != 6
print(f"!= -> {es_distinto_de}")

# < -> Es menor que.
es_menor_que = 5 < 6
print(f"< -> {es_menor_que}")

# <= -> Es menor o igual que.
es_menor_o_igual_que = 5 <= 6
print(f"<= -> {es_menor_o_igual_que}")

# > -> Es mayor que.
es_mayor_que = 5 > 6
print(f"> -> {es_mayor_que}")

# >= -> Es mayor o igual que.
es_mayor_o_igual_que = 5 >= 6
print(f">= -> {es_mayor_o_igual_que}")