# and (&)
print("------------------and-------------------")
result = True & True # devuelve true
print(result)
result = False & True # devuelve false
print(result)
result = True & False # devuelve false
print(result)
result = False & False # devuelve false
print(result)

# or (|)
print("-------------------or-------------------")
result = True | True # devuelve true
print(result)
result = False | True # devuelve true
print(result)
result = True | False # devuelve true
print(result)
result = False | False # devuelve false
print(result)

# not (not)
print("------------------not-------------------")
result = not True # devuelve false
print(result)
result = not False # devuelve true
print(result)