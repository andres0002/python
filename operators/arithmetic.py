# suma y resta (+ y -).
suma = 12 + 5
print(f"Sum: {suma}.")
resta = 15 - 5
print(f"Rest: {resta}.")

# multiplicación y división (* y /).
mult = 12 * 10
print(f"Mult: {mult}.")
div = 12 / 6 # devuelve un dato float.
print(f"Div: {div}.")

# potenciación (exponente) (**).
exp = 12 ** 2
print(f"Exp: {exp}.")

# división baja (//).
div_baja = 12 // 6 # devuelve entero redondeado hacia abajo.
print(f"Div_baja: {div_baja}.")

# modulo o resto (%)
resto = 12 % 6
print(f"Resto: {resto}.")